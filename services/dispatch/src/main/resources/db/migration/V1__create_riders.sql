-- Riders: the dispatch service's own table (schema "dispatch").
-- status: AVAILABLE can take an assignment, BUSY has one, OFFLINE takes none.
-- version: incremented on each change to the rider row (optimistic concurrency, used from step 2).
CREATE TABLE riders (
    id          UUID         PRIMARY KEY,                 -- UUIDv7, generated by the application
    name        TEXT         NOT NULL,
    city        TEXT         NOT NULL,
    status      TEXT         NOT NULL DEFAULT 'AVAILABLE'
                CHECK (status IN ('AVAILABLE', 'BUSY', 'OFFLINE')),
    version     INTEGER      NOT NULL DEFAULT 0,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);
