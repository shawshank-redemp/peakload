-- Orders. The source of truth for order state.
-- status: current state, checked against the allowed set (the transition rules live in code, step 3).
-- version: incremented on every status change; an update that finds a different version is rejected
--          (optimistic concurrency, so two writers cannot silently overwrite each other).
CREATE TABLE orders (
    id          UUID         PRIMARY KEY,                 -- UUIDv7, generated by the application
    client_id   TEXT         NOT NULL,                    -- who placed the order
    status      TEXT         NOT NULL
                CHECK (status IN ('CREATED', 'CONFIRMED', 'PREPARING', 'READY',
                                  'PICKED_UP', 'DELIVERED', 'CANCELLED')),
    version     BIGINT       NOT NULL DEFAULT 0,
    payload     JSONB        NOT NULL,                    -- the order body as sent by the client
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);
